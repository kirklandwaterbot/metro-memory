import lineBadgeFitData from '@/lib/lineBadgeFit.json'
import { Line } from '@/lib/types'
import clsx from 'clsx'
import Image from 'next/image'

export type LineBadgeShape = NonNullable<Line['badgeShape']>
export type LineBadgeFit = NonNullable<Line['badgeFit']>
export type LineBadgeSize = 'small' | 'medium'

type LineBadgeMetrics = {
  width: number
  height: number
  radius: number
  padding: number
}

type LineBadgeProps = {
  lineId: string
  line?: Partial<Line> | null
  iconBasePath?: string | null
  size?: LineBadgeSize
  defaultFit?: LineBadgeFit
  alt?: string
  className?: string
  imageClassName?: string
  maxWidth?: number
}

const LINE_BADGE_METRICS: Record<LineBadgeSize, Record<LineBadgeShape, LineBadgeMetrics>> = {
  small: {
    circle: {
      width: 24,
      height: 24,
      radius: 999,
      padding: 0,
    },
    capsule: {
      width: 60,
      height: 24,
      radius: 8,
      padding: 0,
    },
    wide: {
      width: 88,
      height: 24,
      radius: 8,
      padding: 0,
    },
    square: {
      width: 24,
      height: 24,
      radius: 6,
      padding: 0,
    },
    // a diamond icon (e.g. NYC express services) shown whole, not cropped to a circle
    diamond: {
      width: 24,
      height: 24,
      radius: 0,
      padding: 0,
    },
  },
  medium: {
    circle: {
      width: 40,
      height: 40,
      radius: 999,
      padding: 0,
    },
    capsule: {
      width: 96,
      height: 40,
      radius: 12,
      padding: 0,
    },
    wide: {
      width: 136,
      height: 40,
      radius: 12,
      padding: 0,
    },
    square: {
      width: 40,
      height: 40,
      radius: 10,
      padding: 0,
    },
    diamond: {
      width: 40,
      height: 40,
      radius: 0,
      padding: 0,
    },
  },
}

export const getLineBadgeMetrics = (
  shape: LineBadgeShape = 'circle',
  size: LineBadgeSize = 'small',
  aspectRatio?: number | null,
) => {
  const metrics = LINE_BADGE_METRICS[size][shape]

  if (
    aspectRatio &&
    Number.isFinite(aspectRatio) &&
    aspectRatio > 0 &&
    (shape === 'wide' || shape === 'capsule')
  ) {
    return {
      ...metrics,
      width: Math.round(metrics.height * aspectRatio),
    }
  }

  return metrics
}

type LineBadgeFitEntry = {
  /** Plate position inside the image: [x, y, width, height] as fractions. */
  crop: [number, number, number, number]
  /** Width / height of the plate. */
  aspectRatio: number
}

const LINE_BADGE_FIT = lineBadgeFitData as unknown as Record<string, LineBadgeFitEntry>

// Square badges show a plate edge to edge only if it is close to square;
// anything further off would lose too much of the plate, so it is shown as before.
const MAX_SQUARE_MISMATCH = 0.15

/**
 * Auto-fit data for a line's badge image (generated by scripts/fit-line-badges.js):
 * where the solid plate sits inside the image, ignoring white/transparent margins.
 */
export const getLineBadgeFit = (
  line?: Pick<Partial<Line>, 'icon' | 'badgeShape'> | null,
): LineBadgeFitEntry | null => {
  const shape = line?.badgeShape ?? 'circle'
  const icon = line?.icon
  if (shape === 'circle' || shape === 'diamond' || !icon || !icon.includes('/')) return null
  const entry = LINE_BADGE_FIT[icon.replace(/^\/+/, '').replace(/^images\//, '')]
  if (!entry) return null
  if (shape === 'square' && Math.abs(Math.log(entry.aspectRatio)) > Math.log(1 + MAX_SQUARE_MISMATCH)) {
    return null
  }
  return entry
}

/** Aspect ratio to size a wide/capsule badge (and its progress ring) with. */
export const getLineBadgeAspectRatio = (
  line?: Pick<Partial<Line>, 'icon' | 'badgeShape' | 'badgeAspectRatio'> | null,
) => getLineBadgeFit(line)?.aspectRatio ?? line?.badgeAspectRatio

/** Position the image so its plate exactly covers a width x height box. */
const placePlate = (fit: LineBadgeFitEntry, width: number, height: number) => {
  const [cropX, cropY, cropW, cropH] = fit.crop
  let plateWidth = width
  let plateHeight = width / fit.aspectRatio
  if (plateHeight < height) {
    plateHeight = height
    plateWidth = height * fit.aspectRatio
  }
  const imageWidth = plateWidth / cropW
  const imageHeight = plateHeight / cropH
  return {
    width: imageWidth,
    height: imageHeight,
    left: -cropX * imageWidth - (plateWidth - width) / 2,
    top: -cropY * imageHeight - (plateHeight - height) / 2,
  }
}

export const resolveLineBadgeSrc = ({
  lineId,
  line,
  iconBasePath,
}: {
  lineId: string
  line?: Partial<Line> | null
  iconBasePath?: string | null
}) => {
  const icon = line?.icon
  if (icon) {
    if (icon.includes('/')) {
      return `/images/${icon}`
    }
    if (iconBasePath) {
      return `/images/${iconBasePath.replace(/^\//, '')}/${icon}`
    }
    return `/images/${icon}`
  }

  if (iconBasePath) {
    return `/images/${iconBasePath.replace(/^\//, '')}/${lineId}.svg`
  }

  return `/images/${lineId}.svg`
}

const LineBadge = ({
  lineId,
  line,
  iconBasePath,
  size = 'small',
  defaultFit = 'cover',
  alt,
  className,
  imageClassName,
  maxWidth,
}: LineBadgeProps) => {
  const shape = line?.badgeShape ?? 'circle'
  const plateFit = getLineBadgeFit(line)
  const fit = line?.badgeFit ?? (shape === 'diamond' ? 'contain' : defaultFit)
  const metrics = getLineBadgeMetrics(shape, size, getLineBadgeAspectRatio(line))
  const scale =
    maxWidth && metrics.width > maxWidth ? maxWidth / metrics.width : 1
  const renderedWidth = Math.round(metrics.width * scale)
  const renderedHeight = Math.round(metrics.height * scale)
  const renderedRadius = metrics.radius === 999 ? 999 : Math.round(metrics.radius * scale)
  const renderedPadding = Math.round(metrics.padding * scale)
  const src = resolveLineBadgeSrc({ lineId, line, iconBasePath })

  if (plateFit) {
    // Crop to the plate and round it to the badge's corners, so it sits flush
    // inside the progress ring with no margin, hairline or corner overhang.
    const innerWidth = renderedWidth - renderedPadding * 2
    const innerHeight = renderedHeight - renderedPadding * 2
    const placement = placePlate(plateFit, innerWidth, innerHeight)
    return (
      <div
        className={clsx('relative shrink-0 overflow-hidden', className)}
        style={{
          width: renderedWidth,
          height: renderedHeight,
          borderRadius: renderedRadius,
        }}
      >
        <div
          className="absolute overflow-hidden"
          style={{
            inset: renderedPadding,
            borderRadius: Math.max(renderedRadius - renderedPadding, 0),
          }}
        >
          <div className="absolute" style={placement}>
            <Image
              alt={alt ?? line?.name ?? lineId}
              src={src}
              fill
              sizes={`${Math.ceil(placement.width)}px`}
              quality={100}
              unoptimized
              className={clsx('object-fill', imageClassName)}
            />
          </div>
        </div>
      </div>
    )
  }

  return (
    <div
      className={clsx(
        'relative shrink-0',
        fit === 'contain' ? 'overflow-visible' : 'overflow-hidden',
        className,
      )}
      style={{
        width: renderedWidth,
        height: renderedHeight,
        borderRadius: renderedRadius,
      }}
    >
      <div
        className={clsx(
          'absolute',
          fit === 'contain' ? 'overflow-visible' : 'overflow-hidden',
        )}
        style={{
          inset: renderedPadding,
          borderRadius: Math.max(renderedRadius - renderedPadding, 0),
        }}
      >
        <Image
          alt={alt ?? line?.name ?? lineId}
          src={src}
          fill
          sizes={`${renderedWidth}px`}
          quality={100}
          unoptimized
          className={clsx(
            fit === 'contain' ? 'object-contain' : 'object-cover',
            imageClassName,
          )}
        />
      </div>
    </div>
  )
}

export default LineBadge
