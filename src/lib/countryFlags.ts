export function getFlagEmojiFromCountryCode(countryCode: string) {
  return countryCode
    .toUpperCase()
    .replace(/./g, (character) => String.fromCodePoint(127397 + character.charCodeAt(0)))
}

/** ISO 3166-1 alpha-2 code for a country folder slug ("south-korea" -> "KR"). */
export function getCountryCodeFromSlug(slug: string | null | undefined) {
  return slug ? (COUNTRY_SLUG_TO_ISO_CODE[slug] ?? null) : null
}

export function getCityFlagEmojiFromPath(path: string) {
  const pathSegments = path.split('/').filter(Boolean)
  const countrySlug = pathSegments[1]
  const countryCode = getCountryCodeFromSlug(countrySlug)
  return countryCode ? getFlagEmojiFromCountryCode(countryCode) : '\u{1F310}'
}
